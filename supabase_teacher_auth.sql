-- 1. إضافة حقول الدخول والصلاحيات والمادة لجدول teachers
ALTER TABLE public.teachers
  ADD COLUMN IF NOT EXISTS username text,
  ADD COLUMN IF NOT EXISTS password text,
  ADD COLUMN IF NOT EXISTS course_id bigint references public.courses(id) on delete set null,
  ADD COLUMN IF NOT EXISTS can_add_videos boolean default true,
  ADD COLUMN IF NOT EXISTS can_add_files boolean default true,
  ADD COLUMN IF NOT EXISTS can_create_quizzes boolean default true,
  ADD COLUMN IF NOT EXISTS can_view_students boolean default true;

-- 2. جدول ملفات ومذكرات المدرسين (PDF & Documents)
CREATE TABLE IF NOT EXISTS public.teacher_files (
  id bigint generated by default as identity primary key,
  teacher_id bigint references public.teachers(id) on delete cascade,
  course_id bigint references public.courses(id) on delete cascade,
  lesson_id bigint references public.lessons(id) on delete cascade,
  title text not null,
  file_url text not null,
  file_type text default 'pdf',
  file_size text,
  created_at timestamptz default now()
);

-- إذا كان الجدول موجوداً بالفعل، يتم إضافة العمود lesson_id
ALTER TABLE public.teacher_files
  ADD COLUMN IF NOT EXISTS lesson_id bigint references public.lessons(id) on delete cascade;

-- RLS Policies
ALTER TABLE public.teacher_files ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow public read teacher_files') THEN
    CREATE POLICY "Allow public read teacher_files" ON public.teacher_files FOR SELECT USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Allow service role all teacher_files') THEN
    CREATE POLICY "Allow service role all teacher_files" ON public.teacher_files FOR ALL USING (true);
  END IF;
END $$;
