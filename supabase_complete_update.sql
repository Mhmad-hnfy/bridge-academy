-- 1. إضافة حقول الدخول والصلاحيات والمادة لجدول teachers
ALTER TABLE public.teachers
  ADD COLUMN IF NOT EXISTS username text,
  ADD COLUMN IF NOT EXISTS password text,
  ADD COLUMN IF NOT EXISTS course_id bigint references public.courses(id) on delete set null,
  ADD COLUMN IF NOT EXISTS can_add_videos boolean default true,
  ADD COLUMN IF NOT EXISTS can_add_files boolean default true,
  ADD COLUMN IF NOT EXISTS can_create_quizzes boolean default true,
  ADD COLUMN IF NOT EXISTS can_view_students boolean default true;

-- 2. جدول ملفات ومذكرات المدرسين (PDF & Documents)
CREATE TABLE IF NOT EXISTS public.teacher_files (
  id bigint generated by default as identity primary key,
  teacher_id bigint references public.teachers(id) on delete cascade,
  course_id bigint references public.courses(id) on delete cascade,
  title text not null,
  file_url text not null,
  file_type text default 'pdf',
  file_size text,
  created_at timestamptz default now()
);

-- 3. بنك الامتحانات (مرتبط بالمادة/الكورس)
CREATE TABLE IF NOT EXISTS public.exam_banks (
  id bigint generated by default as identity primary key,
  name text not null,
  subject_name text not null,
  course_id bigint references public.courses(id) on delete cascade,
  created_by_admin boolean default true,
  created_at timestamptz default now()
);

-- 4. أسئلة الامتحان
CREATE TABLE IF NOT EXISTS public.exam_questions (
  id bigint generated by default as identity primary key,
  exam_bank_id bigint references public.exam_banks(id) on delete cascade,
  question_text text,
  question_image text,
  sort_order int default 0
);

-- 5. خيارات الإجابة لكل سؤال
CREATE TABLE IF NOT EXISTS public.exam_choices (
  id bigint generated by default as identity primary key,
  question_id bigint references public.exam_questions(id) on delete cascade,
  choice_text text not null,
  is_correct boolean default false,
  sort_order int default 0
);

-- 6. ربط الامتحان بدرس معين (الكويز يظهر تحت الدرس)
CREATE TABLE IF NOT EXISTS public.lesson_quizzes (
  id bigint generated by default as identity primary key,
  lesson_id bigint references public.lessons(id) on delete cascade,
  exam_bank_id bigint references public.exam_banks(id) on delete cascade,
  pass_percentage int default 50,
  locks_next_lessons boolean default true,
  retry_hours int default 4,
  created_at timestamptz default now(),
  unique(lesson_id)
);

-- 7. محاولات الطلاب في الامتحانات
CREATE TABLE IF NOT EXISTS public.quiz_attempts (
  id uuid default gen_random_uuid() primary key,
  user_id uuid references public.users(id) on delete cascade,
  lesson_quiz_id bigint references public.lesson_quizzes(id) on delete cascade,
  score int default 0,
  passed boolean default false,
  answers jsonb default '{}',
  can_retry_at timestamptz,
  created_at timestamptz default now()
);

-- 8. شهادات الإتمام
CREATE TABLE IF NOT EXISTS public.certificates (
  id uuid default gen_random_uuid() primary key,
  user_id uuid references public.users(id) on delete cascade,
  chapter_id bigint references public.chapters(id) on delete cascade,
  issued_at timestamptz default now(),
  unique(user_id, chapter_id)
);

-- 9. إشعارات إعادة المحاولة للكويز
CREATE TABLE IF NOT EXISTS public.quiz_retry_notifications (
  id uuid default gen_random_uuid() primary key,
  user_id uuid references public.users(id) on delete cascade,
  lesson_quiz_id bigint references public.lesson_quizzes(id) on delete cascade,
  notify_at timestamptz not null,
  sent boolean default false,
  created_at timestamptz default now()
);

