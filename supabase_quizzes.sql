-- 1. بنك الامتحانات (مرتبط بالمادة/الكورس)
create table if not exists public.exam_banks (
  id bigint generated by default as identity primary key,
  name text not null,
  subject_name text not null,  -- اسم المادة (كيمياء، فيزياء...)
  course_id bigint references public.courses(id) on delete cascade,
  created_by_admin boolean default true,
  created_at timestamptz default now()
);

-- 2. أسئلة الامتحان
create table if not exists public.exam_questions (
  id bigint generated by default as identity primary key,
  exam_bank_id bigint references public.exam_banks(id) on delete cascade,
  question_text text,
  question_image text,    -- رابط صورة السؤال (اختياري)
  sort_order int default 0
);

-- 3. خيارات الإجابة لكل سؤال
create table if not exists public.exam_choices (
  id bigint generated by default as identity primary key,
  question_id bigint references public.exam_questions(id) on delete cascade,
  choice_text text not null,
  is_correct boolean default false,
  sort_order int default 0
);

-- 4. ربط الامتحان بدرس معين (الكويز تحت درس معين)
create table if not exists public.lesson_quizzes (
  id bigint generated by default as identity primary key,
  lesson_id bigint references public.lessons(id) on delete cascade,
  exam_bank_id bigint references public.exam_banks(id) on delete cascade,
  pass_percentage int default 50,
  locks_next_lessons boolean default true,
  retry_hours int default 4,    -- عدد ساعات الانتظار قبل إعادة المحاولة
  duration_minutes int default 0, -- مدة الاختبار بالدقائق (0 تعني مفتوح بدون وقت)
  created_at timestamptz default now(),
  unique(lesson_id)    -- كويز واحد لكل درس
);

-- 5. محاولات الطلاب في الامتحانات
create table if not exists public.quiz_attempts (
  id uuid default uuid_generate_v4() primary key,
  user_id uuid references public.users(id) on delete cascade,
  lesson_quiz_id bigint references public.lesson_quizzes(id) on delete cascade,
  score int default 0,                -- نسبة مئوية 0-100
  passed boolean default false,
  answers jsonb default '{}',         -- { "question_id": "choice_id" }
  can_retry_at timestamptz,           -- وقت السماح بالإعادة (بعد 4 ساعات)
  created_at timestamptz default now()
);

-- 6. شهادات الإتمام
create table if not exists public.certificates (
  id uuid default uuid_generate_v4() primary key,
  user_id uuid references public.users(id) on delete cascade,
  chapter_id bigint references public.chapters(id) on delete cascade,
  issued_at timestamptz default now(),
  unique(user_id, chapter_id)
);

-- 7. إشعارات الكويز (للطالب بعد 4 ساعات)
create table if not exists public.quiz_retry_notifications (
  id uuid default uuid_generate_v4() primary key,
  user_id uuid references public.users(id) on delete cascade,
  lesson_quiz_id bigint references public.lesson_quizzes(id) on delete cascade,
  notify_at timestamptz not null,    -- وقت الإشعار
  sent boolean default false,
  created_at timestamptz default now()
);

